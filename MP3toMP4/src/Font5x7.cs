    // Classic 5x7 pixel font (ASCII 0x20 - 0x7E). Column-wise, bit 0 = top row,
    // bit 6 = baseline, bit 7 = descender (g, j, p, q, y).
    internal static class Font5x7
    {
        internal const int Advance = 6;

        internal static int Index(char c)
        {
            if (c < 0x20 || c > 0x7E)
                return '?' - 0x20;
            return c - 0x20;
        }

        // Map umlauts etc. to ASCII, everything else becomes '?'.
        internal static string Sanitize(string s)
        {
            if (string.IsNullOrEmpty(s))
                return "";
            var sb = new StringBuilder(s.Length + 8);
            foreach (char c in s)
            {
                switch (c)
                {
                    case 'ä': sb.Append("ae"); break;
                    case 'ö': sb.Append("oe"); break;
                    case 'ü': sb.Append("ue"); break;
                    case 'Ä': sb.Append("Ae"); break;
                    case 'Ö': sb.Append("Oe"); break;
                    case 'Ü': sb.Append("Ue"); break;
                    case 'ß': sb.Append("ss"); break;
                    case 'é': case 'è': case 'ê': sb.Append('e'); break;
                    case 'á': case 'à': case 'â': sb.Append('a'); break;
                    case 'ó': case 'ò': case 'ô': sb.Append('o'); break;
                    case 'ú': case 'ù': case 'û': sb.Append('u'); break;
                    case 'í': case 'ì': case 'î': sb.Append('i'); break;
                    case 'ñ': sb.Append('n'); break;
                    case 'ç': sb.Append('c'); break;
                    case '–': case '—': sb.Append('-'); break;
                    case '‘': case '’': sb.Append('\''); break;
                    case '“': case '”': case '„': sb.Append('"'); break;
                    case '\t': case '\r': case '\n': sb.Append(' '); break;
                    default:
                        sb.Append(c >= 0x20 && c <= 0x7E ? c : '?');
                        break;
                }
            }
            return sb.ToString().Trim();
        }

